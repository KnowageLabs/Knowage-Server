CREATE TABLE SBI_SAML_STATE (
    STATE_ID VARCHAR(128) NOT NULL PRIMARY KEY,
    STATE_KIND VARCHAR(16) NOT NULL,
    SUBJECT_KEY VARCHAR(64),
    PAYLOAD LONGTEXT NOT NULL,
    EXPIRES_AT BIGINT NOT NULL,
    TOKEN_HASH VARCHAR(64),
    ACTIVE INTEGER DEFAULT 1 NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE INDEX SBI_SAML_STATE_SUBJ_IDX ON SBI_SAML_STATE (SUBJECT_KEY, STATE_KIND, ACTIVE);
CREATE INDEX SBI_SAML_STATE_EXP_IDX ON SBI_SAML_STATE (EXPIRES_AT);

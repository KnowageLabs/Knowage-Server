CREATE TABLE SBI_SAML_STATE (
    STATE_ID VARCHAR2(128 CHAR) PRIMARY KEY,
    STATE_KIND VARCHAR2(16 CHAR) NOT NULL,
    SUBJECT_KEY VARCHAR2(64 CHAR),
    PAYLOAD CLOB NOT NULL,
    EXPIRES_AT NUMBER(19) NOT NULL,
    TOKEN_HASH VARCHAR2(64 CHAR),
    ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CHECK (ACTIVE IN (0, 1))
);
CREATE INDEX SBI_SAML_STATE_SUBJ_IDX ON SBI_SAML_STATE (SUBJECT_KEY, STATE_KIND, ACTIVE);
CREATE INDEX SBI_SAML_STATE_EXP_IDX ON SBI_SAML_STATE (EXPIRES_AT);
